module tb_fir_10tap_all_pipe;

reg clk;
reg rst;
reg ce;
reg [1:0] mode;
reg signed [15:0] x_in;

wire signed [31:0] y_out;

/////////////////////////////////////////////////////////
// DUT
/////////////////////////////////////////////////////////

fir_10tap_all_pipe uut (

    .clk(clk),
    .rst(rst),
    .ce(ce),
    .mode(mode),
    .x_in(x_in),
    .y_out(y_out)

);

/////////////////////////////////////////////////////////
// CLOCK
/////////////////////////////////////////////////////////

always #5 clk = ~clk;

/////////////////////////////////////////////////////////
// MONITOR
/////////////////////////////////////////////////////////

always @(posedge clk) begin

    $display("t=%0t | ce=%b | mode=%b | x=%d | y=%d",
             $time, ce, mode, x_in, y_out);

end

/////////////////////////////////////////////////////////
// INPUT TASK
/////////////////////////////////////////////////////////

task apply_inputs;
begin

    x_in = 16'sd0;     #10;
    x_in = 16'sd127;   #10;
    x_in = 16'sd29;    #10;
    x_in = 16'sd127;   #10;
    x_in = -16'sd75;   #10;
    x_in = 16'sd127;   #10;
    x_in = 16'sd127;   #10;
    x_in = 16'sd57;    #10;
    x_in = 16'sd121;   #10;
    x_in = -16'sd128;  #10;

    x_in = 16'sd0;     #10;
    x_in = 16'sd127;   #10;
    x_in = -16'sd121;  #10;
    x_in = -16'sd57;   #10;
    x_in = -16'sd128;  #10;
    x_in = -16'sd127;  #10;
    x_in = 16'sd75;    #10;
    x_in = -16'sd128;  #10;
    x_in = -16'sd29;   #10;
    x_in = -16'sd128;  #10;

    x_in = 16'sd0;     #10;
    x_in = 16'sd127;   #10;
    x_in = -16'sd121;  #10;
    x_in = -16'sd57;   #10;
    x_in = -16'sd128;  #10;
    x_in = -16'sd127;  #10;
    x_in = 16'sd75;    #10;
    x_in = -16'sd128;  #10;
    x_in = -16'sd29;   #10;
    x_in = -16'sd128;  #10;
end
endtask

/////////////////////////////////////////////////////////
// TEST SEQUENCE
/////////////////////////////////////////////////////////

initial begin

    clk = 0;
    rst = 1;
    ce  = 1;
    x_in = 0;
    mode = 0;

    #20;
    rst = 0;

    /////////////////////////////////////
    // LPF
    /////////////////////////////////////

    mode = 2'b00;
    apply_inputs;

    #100;

    /////////////////////////////////////
    // HPF
    /////////////////////////////////////

    mode = 2'b01;
    apply_inputs;

    #100;

    /////////////////////////////////////
    // BPF
    /////////////////////////////////////

    mode = 2'b10;
    apply_inputs;

    #100;

    /////////////////////////////////////
    // BSF
    /////////////////////////////////////

    mode = 2'b11;
    apply_inputs;

    /////////////////////////////////////
    // CLOCK ENABLE TEST
    /////////////////////////////////////

    #100;
    ce = 0;

    #100;
    ce = 1;

    #100;

    $finish;

end

endmodule